/**
 * Extract Mukhi number from natural language (English, Hindi, Hinglish)
 */
export function extractMukhiNumber(message = "") {
  const text = String(message).toLowerCase().trim();

  // 1. Direct digit match: "5 mukhi", "5-mukhi", "5mukhi", "5 face", "mukhi 5"
  const digitMatch = text.match(/(\d+)\s*(?:mukhi|muki|face|facet|mukha)/i) || 
                     text.match(/(?:mukhi|muki|face)\s*(\d+)/i);
  if (digitMatch && digitMatch[1]) {
    const num = parseInt(digitMatch[1], 10);
    if (num >= 1 && num <= 21) return String(num);
  }

  // 2. Hindi word match: "paanch mukhi", "saat mukhi", "gyarah mukhi", "ek mukhi"
  for (const [word, num] of Object.entries(HINDI_NUMBER_WORDS)) {
    const regex = new RegExp(`\\b${word}\\s*(?:mukhi|muki|face|mukha)?\\b`, "i");
    if (regex.test(text)) {
      if (text.includes("mukhi") || text.includes("rudraksha") || text.includes("rudraksh") || ["ek", "do", "teen", "chaar", "paanch", "chhe", "saat", "aath", "nau", "das", "gyarah", "barah", "terah", "chaudah"].includes(word)) {
        return String(num);
      }
    }
  }

  // 3. Special names
  if (text.includes("gauri shankar") || text.includes("gaurishankar")) return "gauri_shankar";
  if (text.includes("ganesh rudraksha") || text.includes("ganesha rudraksha")) return "ganesh";
  if (text.includes("mala") || text.includes("jaap") || text.includes("japa") || text.includes("108") || text.includes("kanthi")) return "mala";

  return null;
}

