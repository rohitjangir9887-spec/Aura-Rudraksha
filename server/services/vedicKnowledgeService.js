/**
 * Extract Mukhi number or special bead from natural language (English, Hindi, Hinglish)
 */
export function extractMukhiNumber(message = "") {
  const text = String(message).toLowerCase().trim();

  // 1. Direct digit match: "21 mukhi", "5 mukhi", "5-mukhi", "5mukhi", "5 face", "mukhi 5"
  const digitMatch = text.match(/(\d+)\s*(?:mukhi|muki|face|facet|mukha)/i) || 
                     text.match(/(?:mukhi|muki|face)\s*(\d+)/i);
  if (digitMatch && digitMatch[1]) {
    const num = parseInt(digitMatch[1], 10);
    if (num >= 1 && num <= 21) return String(num);
  }

  // 2. Hindi word match: "ikkis mukhi", "saat mukhi", "gyarah mukhi", "ek mukhi"
  for (const [word, num] of Object.entries(HINDI_NUMBER_WORDS)) {
    const regex = new RegExp(`\\b${word}\\s*(?:mukhi|muki|face|mukha)?\\b`, "i");
    if (regex.test(text)) {
      if (text.includes("mukhi") || text.includes("rudraksha") || text.includes("rudraksh") || [
        "ek", "do", "teen", "chaar", "paanch", "chhe", "saat", "aath", "nau", "das",
        "gyarah", "barah", "terah", "chaudah", "pandrah", "solah", "satrah", "atharah", "unnis", "bees", "ikkis"
      ].includes(word)) {
        return String(num);
      }
    }
  }

  // 3. Special names
  if (text.includes("gauri shankar") || text.includes("gaurishankar")) return "gauri_shankar";
  if (text.includes("garbh gauri") || text.includes("garbhgauri")) return "garbh_gauri";
  if (text.includes("trijuti") || text.includes("tri juti") || text.includes("tribhagi")) return "trijuti";
  if (text.includes("ganesh rudraksha") || text.includes("ganesha rudraksha") || (text.includes("ganesh") && text.includes("rudraksh"))) return "ganesh";
  if (text.includes("mala") || text.includes("jaap") || text.includes("japa") || text.includes("108") || text.includes("kanthi")) return "mala";

  return null;
}

/**
 * Check if a bead/mukhi is in the current live store catalog
 */
export function isProductInStoreCatalog(mukhiKey, products = []) {
  if (!mukhiKey || !Array.isArray(products) || products.length === 0) return { available: false, product: null };

  if (mukhiKey === "mala") {
    const found = products.find(p => {
      const n = (p.name || "").toLowerCase();
      const h = (p.highlight || "").toLowerCase();
      return (n.includes("mala") || n.includes("108") || h.includes("japa") || h.includes("mala")) && p.inStock !== false;
    });
    return { available: Boolean(found), product: found || null };
  }

  if (mukhiKey === "gauri_shankar") {
    const found = products.find(p => (p.name || "").toLowerCase().includes("gauri") && p.inStock !== false);
    return { available: Boolean(found), product: found || null };
  }

  if (mukhiKey === "ganesh") {
    const found = products.find(p => (p.name || "").toLowerCase().includes("ganesh") && p.inStock !== false);
    return { available: Boolean(found), product: found || null };
  }

  const num = parseInt(mukhiKey, 10);
  if (!isNaN(num)) {
    const found = products.find(p => {
      const n = (p.name || "").toLowerCase();
      return (n.includes(`${num} mukhi`) || n.includes(`${num}-mukhi`) || n.includes(`${num}mukhi`)) && p.inStock !== false;
    });
    return { available: Boolean(found), product: found || null };
  }

  return { available: false, product: null };
}

