/**
 * Deterministically select high-relevance search keywords for any product
 * based on its attributes without spamming or exceeding natural keyword limits.
 */
export function selectKeywordsForProduct(product = {}) {
  const name = String(product.name || "").trim();
  const category = String(product.category || "").toLowerCase();
  const mukhi = String(product.mukhi || "").replace(/\D/g, "");
  const origin = String(product.origin || "Nepal").toLowerCase();

  const selected = new Set();

  // 1. Identify Mukhi Specific terms
  if (mukhi && SEO_KEYWORD_TAXONOMY.mukhis[mukhi]) {
    const mData = SEO_KEYWORD_TAXONOMY.mukhis[mukhi];
    mData.terms.forEach(t => selected.add(t.phrase));
  } else if (/gauri\s*shankar/i.test(name)) {
    SEO_KEYWORD_TAXONOMY.mukhis["gauri-shankar"]?.terms.forEach(t => selected.add(t.phrase));
  } else if (/ganesh/i.test(name)) {
    SEO_KEYWORD_TAXONOMY.mukhis["ganesh"]?.terms.forEach(t => selected.add(t.phrase));
  }

  // 2. Mala / Combination items
  if (category.includes("mala") || name.toLowerCase().includes("mala")) {
    selected.add("108 beads Rudraksha mala");
    selected.add("Rudraksha Japa Mala");
    selected.add("original 108+1 Rudraksha mala");
  }

  // 3. Origin specific
  if (origin.includes("nepal")) {
    selected.add("Nepal Rudraksha");
    selected.add("Nepali Rudraksha");
  } else if (origin.includes("indo") || origin.includes("java")) {
    selected.add("Indonesian Rudraksha");
    selected.add("Java Rudraksha");
  }

  // 4. Core Brand & Authenticity
  selected.add("Aura Rudraksha");
  selected.add("lab certified Rudraksha");

  return Array.from(selected).slice(0, 8);
}
